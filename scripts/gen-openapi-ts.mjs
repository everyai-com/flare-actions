// Generates apps/worker/src/openapi-spec.ts from openapi.yaml so the
// worker serves its own contract at GET /openapi.yaml, and
// apps/worker/src/llms-text.ts from llms.txt for GET /llms.txt. Deterministic:
// same input bytes always produce the same output bytes, and CI fails
// when the committed module drifts from the spec.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const yaml = readFileSync(join(root, "openapi.yaml"), "utf8");
const out =
  `// GENERATED by scripts/gen-openapi-ts.mjs — do not edit by hand.\n` +
  `// Regenerate with: npm run openapi:gen\n` +
  `export const OPENAPI_YAML: string = ${JSON.stringify(yaml)};\n`;
writeFileSync(join(root, "apps/worker/src/openapi-spec.ts"), out);
console.log(`openapi-spec.ts OK: ${yaml.length} chars`);

const llms = readFileSync(join(root, "llms.txt"), "utf8");
writeFileSync(
  join(root, "apps/worker/src/llms-text.ts"),
  `// GENERATED by scripts/gen-openapi-ts.mjs — do not edit by hand.\n` +
    `// Regenerate with: npm run openapi:gen\n` +
    `export const LLMS_TXT: string = ${JSON.stringify(llms)};\n`,
);
console.log(`llms-text.ts OK: ${llms.length} chars`);
